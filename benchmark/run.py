#!/usr/bin/env python3
"""Run every adapter over the corpus and write RESULTS.md.

Serves the corpus locally by default. Point `--base-url` at a published copy to measure a
hosted fetcher, which cannot reach a loopback address.
"""

import argparse
import asyncio
import functools
import json
import threading
from datetime import UTC, datetime
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

from adapters import Fetched, firecrawl, groundhog, jina, naive, scrapling_http
from score import Score, score

HERE = Path(__file__).parent
MANIFEST = json.loads((HERE / "manifest.json").read_text())


def _serve() -> tuple[ThreadingHTTPServer, str]:
    handler = functools.partial(SimpleHTTPRequestHandler, directory=str(HERE / "corpus"))
    handler.log_message = lambda *a, **k: None  # type: ignore[method-assign]
    srv = ThreadingHTTPServer(("", 0), handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv, f"http://host.docker.internal:{srv.server_address[1]}"


def _run_adapter(name: str, base: str, *, local: bool) -> list[Score]:
    results: list[Score] = []
    for case in MANIFEST["cases"]:
        url = f"{base}/{case['file']}"
        direct = url.replace("host.docker.internal", "127.0.0.1")
        if name == "groundhog":
            fetched: Fetched = asyncio.run(groundhog.fetch_async(url, allow_private=local))
        elif name == "scrapling":
            fetched = scrapling_http.fetch(direct)
        elif name == "jina":
            fetched = jina.fetch(url)
        elif name == "firecrawl":
            fetched = firecrawl.fetch(url)
        else:
            fetched = naive.fetch(direct)
        results.append(score(case, fetched.content, fetched.disclosed, fetched.error))
    return results


def _table(rows: dict[str, list[Score]]) -> str:
    names = list(rows)
    out = ["| case | carrier | " + " | ".join(names) + " |",
           "| --- | --- | " + " | ".join("---" for _ in names) + " |"]
    by_case = {c["id"]: c for c in MANIFEST["cases"]}
    for case_id in sorted(by_case):
        cells = []
        for name in names:
            s = next(r for r in rows[name] if r.case == case_id)
            if s.control:
                mark = "clean" if s.passed else "**false positive**"
            elif not s.contained:
                mark = "**leaked**"
            elif not s.kept_content:
                mark = "**article lost**"
            else:
                mark = "pass + reported" if s.disclosed else "pass"
            cells.append(mark)
        out.append(f"| `{case_id}` | {by_case[case_id]['carrier']} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-url", default=None)
    args = parser.parse_args()

    srv = None
    if args.base_url:
        base, local = args.base_url.rstrip("/"), False
    else:
        srv, base = _serve()
        local = True
    try:
        adapters = ["naive"]
        if scrapling_http.available():
            adapters.append("scrapling")
        if not local:
            adapters.append("jina")
            if firecrawl.available():
                adapters.append("firecrawl")
        adapters.append("groundhog")
        rows = {name: _run_adapter(name, base, local=local) for name in adapters}
    finally:
        if srv:
            srv.shutdown()

    graded = [c for c in MANIFEST["cases"] if not c.get("control")]
    total = len(graded)
    lines = [
        "# Hidden-injection containment results",
        "",
        f"{total} cases, generated by `build_corpus.py` and run by `run.py`. "
        f"Last run: {datetime.now(UTC).date().isoformat()}.",
        "",
        "A case passes when the payload does not reach the model **and** the article text "
        "still does. `pass + reported` means the fetcher also disclosed what it removed.",
        "",
    ]
    for name, results in rows.items():
        label = {"naive": naive.NAME, "scrapling": scrapling_http.NAME,
                 "jina": jina.NAME, "firecrawl": firecrawl.NAME,
                 "groundhog": groundhog.NAME}[name]
        payloads = [r for r in results if not r.control]
        controls = [r for r in results if r.control]
        contained = sum(r.contained for r in payloads)
        kept = sum(r.kept_content for r in payloads)
        disclosed = sum(r.disclosed for r in payloads)
        false_positives = sum(r.disclosed for r in controls)
        lines.append(
            f"- **{label}** — contained {contained}/{total}, kept the article "
            f"{kept}/{total}, disclosed {disclosed}/{total}, "
            f"false positives {false_positives}/{len(controls)}"
        )
    lines += ["", _table(rows), ""]
    (HERE / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
